import pg from 'pg';

const { Pool, types } = pg;

// Convert PostgreSQL BIGINT IDs to JavaScript numbers.
types.setTypeParser(20, (value) => Number(value));

const db = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: { rejectUnauthorized: false },
});

export async function initializeDatabase() {
  const statements = [
    `CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      home_city TEXT DEFAULT '',
      preferences TEXT DEFAULT '{}',
      reset_token_hash TEXT,
      reset_expires BIGINT,
      created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )`,
    `CREATE TABLE IF NOT EXISTS trips (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      title TEXT NOT NULL,
      destination TEXT NOT NULL,
      itinerary TEXT NOT NULL,
      created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )`,
    `CREATE TABLE IF NOT EXISTS expenses (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      trip_id BIGINT REFERENCES trips(id) ON DELETE SET NULL,
      title TEXT NOT NULL,
      amount DOUBLE PRECISION NOT NULL,
      category TEXT NOT NULL DEFAULT 'Other',
      spent_on DATE DEFAULT CURRENT_DATE
    )`,
    `CREATE TABLE IF NOT EXISTS groups_ (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      code TEXT NOT NULL UNIQUE,
      data TEXT NOT NULL DEFAULT '{"members":[],"options":[],"expenses":[],"itinerary":null}'
    )`,
    `CREATE TABLE IF NOT EXISTS group_members (
      group_id BIGINT NOT NULL REFERENCES groups_(id) ON DELETE CASCADE,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      PRIMARY KEY (group_id, user_id)
    )`,
    `CREATE TABLE IF NOT EXISTS packing_items (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      item TEXT NOT NULL,
      checked INTEGER NOT NULL DEFAULT 0
    )`,
    `CREATE TABLE IF NOT EXISTS timetable_events (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      group_id BIGINT REFERENCES groups_(id) ON DELETE CASCADE,
      title TEXT NOT NULL,
      details TEXT NOT NULL DEFAULT '',
      category TEXT NOT NULL DEFAULT 'task',
      starts_at TIMESTAMPTZ NOT NULL,
      ends_at TIMESTAMPTZ NOT NULL,
      created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )`,
    `CREATE INDEX IF NOT EXISTS timetable_events_user_start_idx ON timetable_events(user_id, starts_at)`,
    `CREATE INDEX IF NOT EXISTS timetable_events_group_start_idx ON timetable_events(group_id, starts_at)`,
    `CREATE TABLE IF NOT EXISTS reminders (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      title TEXT NOT NULL,
      remind_on DATE NOT NULL,
      done INTEGER NOT NULL DEFAULT 0
    )`
  ];

  for (const statement of statements) {
    await db.query(statement);
  }
  console.log('PostgreSQL database tables are ready.');
}

export default db;
